// Dijkstra over ordered triples of positions: macro = S + core + S^-1 for every 3-cycle.
import fs from 'fs';
import { getGeometry, movePerm } from '../src/engine/cube.js';
import { getPieces } from '../src/engine/pieces.js';

const N = 4, geo = getGeometry(N), P = getPieces();
const raw = JSON.parse(fs.readFileSync(new URL('./cores_raw.json', import.meta.url), 'utf8'));
const FL = ['U', 'R', 'F', 'D', 'L', 'B'];
const sfx = (t) => (t === 1 ? '' : t === 2 ? '2' : "'");
const base = [];
for (const F of FL) for (const t of [1, 2, 3]) {
  base.push({ name: F + sfx(t), inv: F + sfx((4 - t) % 4), perm: movePerm(geo, F, 0, 0, t) });
  base.push({ name: '2' + F + sfx(t), inv: '2' + F + sfx((4 - t) % 4), perm: movePerm(geo, F, 1, 1, t) });
  base.push({ name: F + 'w' + sfx(t), inv: F + 'w' + sfx((4 - t) % 4), perm: movePerm(geo, F, 0, 1, t) });
}
const invName = (tok) => (tok.endsWith("'") ? tok.slice(0, -1) : tok.endsWith('2') ? tok : tok + "'");
const invAlg = (a) => a.split(' ').reverse().map(invName).join(' ');

function build(type) {
  const sts = type === 'wing' ? P.wings.map((w) => w.stickers[0]) : P.centers.map((c) => c.sticker);
  const posOf = type === 'wing' ? P.wingOfSticker : P.centerOfSticker;
  // position map for each base move
  const maps = base.map((b) => sts.map((s) => posOf[b.perm[s]]));
  const idx = (a, b, c) => (a * 24 + b) * 24 + c;
  const dist = new Map(), pred = new Map();
  const buckets = [];
  const push = (st, d, p) => { if (!dist.has(st) || d < dist.get(st)) { dist.set(st, d); pred.set(st, p); (buckets[d] ||= []).push(st); } };
  // roots: cores
  const sstate = (core) => core.alg;
  for (const core of raw[type]) {
    // recompute cycle from the recorded alg by simulation of piece movement
    // (core only stores alg + len; derive cycle)
    const seq = core.alg.split(' ');
    let state = Uint8Array.from({ length: 96 }, (_, i) => i); // sticker ids: state[i]=origin id at i
    // apply moves
    for (const tok of seq) {
      const b = base.find((x) => x.name === tok);
      const nxt = new Uint8Array(96);
      for (let i = 0; i < 96; i++) nxt[b.perm[i]] = state[i];
      state = nxt;
    }
    // piece originally at sticker j is now at position i where state[i]=j
    const where = new Map();
    for (let i = 0; i < 96; i++) where.set(state[i], i);
    const moved = [];
    for (let k = 0; k < 24; k++) { const s = sts[k]; if (where.get(s) !== s) moved.push(k); }
    // (for wings, second sticker may stay inside the same position, ok)
    if (moved.length !== 3) continue;
    const a = moved[0], b = posOf[where.get(sts[a])], c = posOf[where.get(sts[b])];
    if (posOf[where.get(sts[c])] !== a) continue;
    for (const [x, y, z] of [[a, b, c], [b, c, a], [c, a, b]]) push(idx(x, y, z), core.len, { root: core.alg });
  }
  for (let d = 0; d < buckets.length; d++) {
    for (const st of buckets[d] || []) {
      if (dist.get(st) !== d) continue;
      const a = Math.floor(st / 576), b = Math.floor(st / 24) % 24, c = st % 24;
      for (let m = 0; m < base.length; m++) {
        const mp = maps[m];
        const nst = idx(mp[a], mp[b], mp[c]);
        push(nst, d + 2, { from: st, move: base[m].inv });
      }
    }
  }
  const table = {};
  let total = 0, cnt = 0, mx = 0;
  for (let a = 0; a < 24; a++) for (let b = 0; b < 24; b++) for (let c = 0; c < 24; c++) {
    if (a === b || b === c || a === c) continue;
    if (!(a < b && a < c)) continue; // canonical rotation: smallest first
    const st = idx(a, b, c);
    if (!dist.has(st)) continue;
    // rebuild alg: walk preds
    const pre = []; let cur = st, p;
    while (!(p = pred.get(cur)).root) { pre.push(p.move); cur = p.from; }
    // pre list: moves prepended later come first? we pushed prepend moves from root outwards:
    // S' = [m'] + S, walking back from st to root gives moves in order (first applied first)
    const S = pre; // st's last prepended move is first applied
    const alg = [...S, p.root, ...S.slice().reverse().map(invName)].join(' ');
    table[`${a},${b},${c}`] = alg; total += dist.get(st); cnt++; mx = Math.max(mx, dist.get(st));
  }
  console.log(type, 'entries', cnt, 'avg cost', (total / cnt).toFixed(1), 'max', mx);
  return table;
}
const out = { wing: build('wing'), center: build('center') };
fs.writeFileSync('src/solver/macroTable.js', '// generated by scripts/buildMacros.mjs\nexport default ' + JSON.stringify(out) + ';\n');
console.log('bytes', fs.statSync('src/solver/macroTable.js').size);
